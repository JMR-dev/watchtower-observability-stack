#!/usr/bin/env bash
# Write the SSH config every SSH to the hosts goes through: Ansible's
# (ansible.cfg passes -F inventory/ssh_config), scripts/verify.sh's and
# yours. Hosts by their inventory names. The nodes always through the
# proxy, on their private addresses: they take no SSH on their public ones,
# only the proxy's private address may reach theirs (roles/firewall), and
# the mesh (wg1) does not exist until the first deploy has made it. Only the
# way to the proxy changes:
#
#   scripts/ssh-config.sh vpn      the tunnel address, from a WireGuard peer.
#                                  With WATCHTOWER_VPN_FORWARD=127.0.0.1:2222,
#                                  that local port instead: wireproxy's TCP
#                                  tunnel to 10.8.0.1:22, the deploy's way in
#   scripts/ssh-config.sh bastion  its public address, which takes SSH only
#                                  from the break-glass bastion
#                                  (breakGlassCidrs), through it over IAP, as the gcloud
#                                  account in use (OS Login with a key made
#                                  here, valid 4 hours). For a service
#                                  account, export
#                                  CLOUDSDK_AUTH_CREDENTIAL_FILE_OVERRIDE
#
#   ssh -F ansible/inventory/ssh_config watchtower-2
#
# Every host key is pinned: inventory/known_hosts (`pulumi stack output
# knownHosts`) and, for the bastion, its key from the inventory
# (bastionHostKey). The root key is ANSIBLE_PRIVATE_KEY_FILE when set (the
# deploy; scripts/env.sh), else whatever ssh-agent offers. Needs the
# inventory (ansible/inventory/hosts.yml) and jq; bastion mode gcloud.

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
dir="${repo_root}/ansible/inventory"
inv="${dir}/hosts.yml"
out="${dir}/ssh_config"
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

mode="${1:-}"
[[ "$mode" =~ ^(vpn|bastion)$ ]] || die "usage: $0 vpn|bastion"
[[ -s "$inv" ]] || die "no ${inv}: pulumi stack output inventory >${inv}"
[[ -s "${dir}/known_hosts" ]] || die "no ${dir}/known_hosts: pulumi stack output knownHosts >${dir}/known_hosts"

var() { jq -r ".all.vars.$1" "$inv"; }
proxy="$(jq -r '.all.children.proxy.hosts | keys[0]' "$inv")"
proxy_public="$(jq -r --arg p "$proxy" '.all.children.proxy.hosts[$p].public_ip' "$inv")"
tunnel="$(var watchtower_tunnel_ip)"

umask 077
{
  echo "# Generated by scripts/ssh-config.sh ${mode}; regenerate rather than edit."

  if [[ "$mode" == bastion ]]; then
    bastion="$(var watchtower_bastion.name)"
    zone="$(var watchtower_bastion.zone)"
    project="$(var watchtower_bastion.project)"
    printf '%s %s\n' "$bastion" "$(var watchtower_bastion.host_key)" >"${dir}/bastion_known_hosts"
    # OS Login acts on gcloud's account, which must be the credential's: a
    # service account's key file names it.
    if [[ -n "${CLOUDSDK_AUTH_CREDENTIAL_FILE_OVERRIDE:-}" ]]; then
      CLOUDSDK_CORE_ACCOUNT="$(jq -r .client_email "$CLOUDSDK_AUTH_CREDENTIAL_FILE_OVERRIDE")"
      export CLOUDSDK_CORE_ACCOUNT
    fi
    # A fresh key each time, in OS Login for 4 hours: nothing to rotate or
    # revoke. OS Login names the account (sa_<id> for a service account).
    key="${dir}/bastion_key"
    rm -f "$key" "${key}.pub"
    ssh-keygen -q -t ed25519 -N '' -C "watchtower $(date -u +%FT%TZ)" -f "$key"
    # gcloud reports the key it added; keep that out of the output unless
    # the call fails.
    err="$(mktemp)"
    if ! profile="$(gcloud compute os-login ssh-keys add --key-file "${key}.pub" --ttl 4h \
      --project "$project" --format json 2>"$err")"; then
      cat "$err" >&2
      rm -f "$err"
      die "OS Login refused the key"
    fi
    rm -f "$err"
    user="$(jq -r '[.loginProfile.posixAccounts[] | select(.primary)][0].username // .loginProfile.posixAccounts[0].username' <<<"$profile")"
    unset profile
    [[ -n "$user" && "$user" != null ]] || die "OS Login returned no username"
    cat <<EOF

Host ${bastion}
  HostName ${bastion}
  User ${user}
  IdentityFile ${key}
  IdentitiesOnly yes
  ProxyCommand gcloud compute start-iap-tunnel ${bastion} 22 --listen-on-stdin --zone ${zone} --project ${project} --verbosity warning
  HostKeyAlias ${bastion}
  UserKnownHostsFile ${dir}/bastion_known_hosts
  StrictHostKeyChecking yes
  BatchMode yes
  ServerAliveInterval 30
EOF
  fi

  echo
  echo "Host ${proxy}"
  case "$mode" in
    bastion)
      echo "  HostName ${proxy_public}"
      echo "  ProxyJump ${bastion}"
      ;;
    vpn)
      if [[ -n "${WATCHTOWER_VPN_FORWARD:-}" ]]; then
        echo "  HostName ${WATCHTOWER_VPN_FORWARD%:*}"
        echo "  Port ${WATCHTOWER_VPN_FORWARD##*:}"
        # The key known_hosts pins for the tunnel address.
        echo "  HostKeyAlias ${tunnel}"
      else
        echo "  HostName ${tunnel}"
      fi
      ;;
  esac

  while read -r node ip; do
    echo
    echo "Host ${node}"
    echo "  HostName ${ip}"
    echo "  ProxyJump ${proxy}"
  done < <(jq -r '.all.children.nodes.hosts | to_entries[] | "\(.key) \(.value.private_ip)"' "$inv")

  echo
  echo "Host * !${bastion:-watchtower-bastion}"
  echo "  User root"
  if [[ -n "${ANSIBLE_PRIVATE_KEY_FILE:-}" ]]; then
    echo "  IdentityFile ${ANSIBLE_PRIVATE_KEY_FILE}"
    echo "  IdentitiesOnly yes"
  fi
  echo "  UserKnownHostsFile ${dir}/known_hosts"
  echo "  StrictHostKeyChecking yes"
  echo "  BatchMode yes"
  echo "  ServerAliveInterval 30"
} >"$out"

echo "wrote ${out} (${mode})" >&2
